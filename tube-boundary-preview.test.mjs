import assert from 'node:assert/strict';
import {beforeOpenEnd,endSelection,tubeEndField,tubeEndFields} from './tube-boundary-preview.js';
const frame=(time,a,b)=>({time,left:0,pressure:[a,2,b],density:[1,1,1],velocity:[0,0,0]});
const source={result:{frames:[frame(0,2,2),frame(.1,2,2),frame(.2,3,2),frame(.3,3,4)],end:.3,left:0,right:1,checks:{mass:5},chart:{title:'Old',series:[{name:'Domain',points:[[0,0],[1,300]]},{name:'Incident',points:[[0,0],[1,300]]}]}},rows:[['Launch wave',1,''],['Final pressure',50,'kPa'],['Simulated time',300,'ms']]};
assert.equal(beforeOpenEnd(source,{}),source);
const left=beforeOpenEnd(source,{tubeLeftBoundary:'Open end'});
assert.equal(left.result.end,.1);
assert.equal(left.result.frames.length,2);
assert.deepEqual(left.result.chart.series[0].points,[[0,0],[1,100]]);
assert.deepEqual(left.rows.map(r=>r[0]),['Launch wave','Displayed time']);
const right=beforeOpenEnd(source,{tubeRightBoundary:'Open end'});
assert.equal(right.result.end,.2);
assert.equal(right.result.frames.length,3);
assert.equal(source.result.frames.length,4);
assert.equal(beforeOpenEnd(source,{tubeLeftBoundary:'Open end',tubeRightBoundary:'Open end'}).result.end,.1);
assert.throws(()=>beforeOpenEnd({...source,result:{...source.result,frames:[frame(0,2,2),frame(.1,3,2)]}},{tubeLeftBoundary:'Open end'}),{code:'boundary-preview-limit'});
assert.equal(endSelection({unsteadyExperiment:'Single-stage piston',tubeLeftBoundary:'Open end'}).left,'Closed end');
assert.equal(endSelection({unsteadyExperiment:'Sudden valve closure',tubeRightBoundary:'Open end'}).right,'Closed end');
assert.equal(tubeEndField(tubeEndFields[0],{unsteadyExperiment:'Sinusoidal piston'}).options.length,1);
console.log('Boundary preview: clipping, unaffected closed mode, and fixed boundaries passed.');
